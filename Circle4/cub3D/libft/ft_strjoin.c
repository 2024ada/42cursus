#include <libft.h>

char	*ft_strjoin(char const *s1, char const *s2)
{
	char	*result;
	size_t	len;

	if (!s1 || !s2)
		return (NULL);
	len = ft_strlen(s1) + ft_strlen(s2);
	result = (char *)ft_xmalloc(len + 1);
	ft_strcpy(result, s1);
	ft_strcpy(result + ft_strlen(s1), s2);
	result[len] = '\0';
	return (result);
}
